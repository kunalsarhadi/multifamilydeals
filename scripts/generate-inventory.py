#!/usr/bin/env python3
"""Generate the Available cards on inventory.html from scripts/inventory-data.json.

Why this exists: the 14 Available cards used to be ~4 KB of hand-copied markup
each, and the page's raw HTML carried hard-coded fallback numbers ("7 available",
"6-8 unit builds, completing 2026", size chips stopping at 8-Plex) that drifted
out of date. A script at the bottom of the page corrected them in the browser,
but Google, link previews and AI tools read the raw HTML and saw the stale text.

This script makes the raw HTML correct:
  * the Available cards between the inventory:cards markers are rebuilt from data
  * the size-filter chips between the inventory:chips markers are rebuilt
  * the hero/status counts, the sold-conditional and previously-sold counts,
    and the "N-M unit builds, completing YYYY" heading are rewritten

Counts for Sold Conditional and Previously Sold are still counted from their
hand-written cards (plus data-sc-extra), exactly as the page script does, so
those sections are untouched.

The page script stays in place and computes the same values at load; the two
always agree because they use the same rules.

Usage:  python3 scripts/generate-inventory.py            (writes inventory.html)
        python3 scripts/generate-inventory.py --check    (exit 1 if out of date)
"""
import html
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAGE = os.path.join(ROOT, 'inventory.html')
DATA = os.path.join(HERE, 'inventory-data.json')

CARDS_START = '<!-- inventory:cards:start — generated by scripts/generate-inventory.py from scripts/inventory-data.json; do not hand-edit -->'
CARDS_END = '<!-- inventory:cards:end -->'
CHIPS_START = '<!-- inventory:chips:start — generated -->'
CHIPS_END = '<!-- inventory:chips:end -->'

e = lambda s: html.escape(str(s), quote=True)
money = lambda n: '${:,.0f}'.format(n)

CHIP_STYLE = ("cursor:pointer;font-family:'Space Grotesk',sans-serif;font-size:.72rem;font-weight:600;"
              "letter-spacing:.1em;text-transform:uppercase;padding:10px 18px;border:1px solid #D9D0C0;"
              "background:transparent;color:#4A443B;border-radius:2px;"
              "transition:background .25s,color .25s,border-color .25s;")

LABEL = "font-size:.6rem;letter-spacing:.12em;text-transform:uppercase;color:#6E6656;"
VALUE = "font-family:'Newsreader',serif;font-size:1.2rem;color:#1C1813;margin-top:3px;"


